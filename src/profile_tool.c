/* Host-only INI inspection and reference-table generation; no PS5 SDK needed. */
#include "hybrid_cache_io.h"
#include "jsc_cache.h"
#include "diagnostics.h"
static void bytes(const uint8_t *data, size_t length) {
    putchar('{');
    for(size_t i=0;i<length;i++)printf("%s0x%02x",i?",":"",data[i]);
    putchar('}');
}
static void entry(const struct hybrid_cache *cache) {
    const struct fixed_profile *p=&cache->profile;
    printf("  {.firmware=0x%08x, .profile={.version=\"%02x.%02x\", .firmware=0x%08x,\n",
           cache->firmware,(cache->firmware>>24)&255,(cache->firmware>>16)&255,p->firmware);
#define FIELD(name) printf("    ." #name "=0x%lx,\n",(unsigned long)p->name)
    FIELD(registry_rva); FIELD(runtime_owner_offset); FIELD(module_list_offset); FIELD(module_runtime_offset);
    FIELD(provider_offset); FIELD(provider_vtable_rva); FIELD(buffer_object_offset); FIELD(buffer_data_offset);
    FIELD(buffer_length_offset); FIELD(fingerprint_rva);
#undef FIELD
    printf("    .fingerprint="); bytes(p->fingerprint,32); printf(", .sources={\n");
    for(unsigned s=0;s<2;s++) {
        const struct fixed_source *source=&p->sources[s];
        printf("      {.header="); bytes(source->header,128);
        printf(", .plan={.count=%u, .patches={\n",source->plan.count);
        for(unsigned i=0;i<source->plan.count;i++) {
            const struct hbc_patch *patch=&source->plan.patches[i];
            printf("        {.name=\"%s\", .offset=0x%x, .length=%u, .before=",patch->name,patch->offset,patch->length);
            bytes(patch->before,patch->length); printf(", .after="); bytes(patch->after,patch->length); printf("},\n");
        }
        printf("      }}},\n");
    }
    printf("    }}},\n");
}
struct record { int jsc; struct hybrid_cache hermes; struct jsc_reference_profile native; };
static uint32_t firmware(const struct record *r) { return r->jsc?r->native.firmware:r->hermes.firmware; }
static int compare(const void *a, const void *b) {
    uint32_t x=firmware(a),y=firmware(b); return (x>y)-(x<y);
}
static void jsc_entry(const struct jsc_reference_profile *p) {
    printf("    {.firmware=0x%08x, .entry_length=%u, .entry_rva=0x%lx, .code_rva=0x%lx, .constants_rva=0x%lx,\n     .fingerprint=",
           p->firmware,p->entry_length,(unsigned long)p->entry_rva,(unsigned long)p->code_rva,(unsigned long)p->constants_rva);
    bytes(p->fingerprint,32); puts("},");
}
int main(int argc, char **argv) {
    int header=argc>1 && !strcmp(argv[1],"--header"), first=header?2:1;
    if(argc<=first || (!header && argc!=2) || argc-first>64) {
        fprintf(stderr,"Usage: %s FILE.ini\n       %s --header FILE.ini [FILE.ini ...]\n",argv[0],argv[0]); return 2;
    }
    size_t count=(size_t)(argc-first);
    struct record *records=calloc(count,sizeof(*records));
    struct diagnostic_report report; int report_result=-1,has_report=0;
    if(!records)return 1;
    for(size_t i=0;i<count;i++) {
        uint8_t data[INI_FILE_CAPACITY]; size_t length=0;
        int result=cache_file_read(argv[first+(int)i],data,sizeof(data),&length);
        if(!result) {
            size_t prefix=ini_profile_length(data,length);
            if(!header && prefix<length) { has_report=1; report_result=diag_decode(data+prefix,length-prefix,&report); }
            if(!hc_decode(data,length,0,&records[i].hermes))records[i].jsc=0;
            else if(!jc_decode(data,length,0,&records[i].native))records[i].jsc=1;
            else result=HC_CONTENT_REJECTED;
        }
        if(result && !header && has_report && !report_result) {
            puts("DIAGNOSTICS ONLY: no validated reusable cache profile"); diag_print(&report); free(records); return 0;
        }
        if(result) { fprintf(stderr,"%s: %s\n",argv[first+(int)i],hc_load_reason(result)); free(records); return 1; }
    }
    qsort(records,count,sizeof(*records),compare);
    for(size_t i=1;i<count;i++)if(firmware(records+i-1)==firmware(records+i) || records[i].jsc!=records[0].jsc) {
        fputs("Use one engine per reference header and one verified record per exact firmware\n",stderr); free(records); return 1;
    }
    if(header && records[0].jsc) {
        puts("/* SPDX-License-Identifier: GPL-3.0-or-later */\n/* Generated by profile-tool --header; review and console-test new entries. */");
        puts("#ifndef WEB_BROWSER_JSC_REFERENCE_PROFILES_H\n#define WEB_BROWSER_JSC_REFERENCE_PROFILES_H\n#include \"jsc_profile_types.h\"\nstatic const struct jsc_reference_profile jsc_reference_profiles[]={");
        for(size_t i=0;i<count;i++)jsc_entry(&records[i].native);
        puts("};\nstatic inline const struct jsc_reference_profile *jsc_profile_for_firmware(uint32_t firmware) {\n    for(unsigned i=0;i<sizeof(jsc_reference_profiles)/sizeof(*jsc_reference_profiles);i++)\n        if(jsc_reference_profiles[i].firmware==firmware)return &jsc_reference_profiles[i];\n    return NULL;\n}\n#endif");
    } else if(header) {
        puts("/* SPDX-License-Identifier: GPL-3.0-or-later */\n/* Generated by profile-tool --header; review and console-test new entries. */");
        puts("#ifndef WEB_BROWSER_HBC_REFERENCE_PROFILES_H\n#define WEB_BROWSER_HBC_REFERENCE_PROFILES_H\n#include \"hybrid_cache.h\"");
        puts("static const struct hybrid_cache reference_profiles[]={");
        for(size_t i=0;i<count;i++)entry(&records[i].hermes);
        puts("};\nstatic inline const struct hybrid_cache *reference_for_firmware(uint32_t firmware) {\n    for(size_t i=0;i<sizeof(reference_profiles)/sizeof(reference_profiles[0]);i++)\n        if(reference_profiles[i].firmware==firmware)return &reference_profiles[i];\n    return NULL;\n}\n#endif");
    } else {
        printf("VALID: INI format %u, CRC verified\nEngine: %s\nFirmware: 0x%08x\n",
               HYBRID_CACHE_VERSION,records[0].jsc?"JSC":"Hermes",firmware(records));
        if(records[0].jsc)jsc_entry(&records[0].native);
        else for(unsigned s=0;s<2;s++)for(unsigned i=0;i<records[0].hermes.profile.sources[s].plan.count;i++) {
            const struct hbc_patch *p=&records[0].hermes.profile.sources[s].plan.patches[i];
            printf("%s %-15s +0x%x (%u bytes)\n",s?"NPXS40003":"NPXS40036",p->name,p->offset,p->length);
        }
        puts("Verify new references independently and on-console before including them.");
        if(has_report) {
            if(report_result)fputs("Diagnostics rejected: malformed section or CRC mismatch\n",stderr);
            else diag_print(&report);
        }
    }
    free(records); return ferror(stdout)?1:0;
}
